# ==================== 1.2.1 什么是程序与编程 ====================
# 程序 = 数据 + 对数据的处理步骤 + 控制流程。
# 编程不是先敲代码，而是先明确输入、输出以及中间的变换规则。
# 例：根据单价、数量、折扣计算订单应付金额。
unit_price = 49.9
quantity = 2
discount_rate = 0.9
subtotal = unit_price * quantity
payable = subtotal * discount_rate
print(f"小计：{subtotal:.2f}，应付：{payable:.2f}")   # -> 小计：99.80，应付：89.82
# // C++: 同样用 double 计算；金额场景更推荐定点数或十进制类型，避免二进制浮点误差。

# ==================== 1.2.2 数据、算法与程序的关系 ====================
# 数据是加工对象，算法是加工步骤，程序是用某种语言写出的可执行描述。
# 以欧几里得算法求最大公约数为例：反复用余数替换两个数，直到余数为 0。
a, b = 252, 105
steps = 0
while b != 0:
    a, b = b, a % b
    steps += 1
print(f"最大公约数：{a}，迭代 {steps} 次")   # -> 最大公约数：21，迭代 3 次
# // C++: C++17 可直接调用 std::gcd(252, 105)；Python 标准库 math.gcd 同样可用。
# 这里手写算法是为了看清“数据如何被一步步变换”，而不是背调用。

# ==================== 1.2.3 从问题到程序的基本过程 ====================
# 步骤一：明确输入与输出。输入年份，输出是否闰年。
# 步骤二：把规则写成可计算表达式。闰年规则：
#   能被 4 整除且不能被 100 整除，或者能被 400 整除。
# 步骤三：用正常值和边界值验证。1900、2000 是最容易写错的边界。
years = [1900, 2000, 2023, 2024, 2100]
for year in years:
    is_leap = (year % 4 == 0 and year % 100 != 0) or year % 400 == 0
    print(f"{year} 是否闰年：{is_leap}")
# -> 1900 是否闰年：False
# -> 2000 是否闰年：True
# -> 2023 是否闰年：False
# -> 2024 是否闰年：True
# -> 2100 是否闰年：False
# // C++: 逻辑运算符写作 && 和 ||，布尔值输出为 0/1；Python 使用 and/or 并输出 True/False。

# 常见坑点：
# 1. 跳过需求分析直接写代码，容易出现“程序能运行但结果不对”。
# 2. 只测试一个正常值，不测试边界值，例如漏掉 1900 和 2000。
# 3. 把 % 当成百分号：在表达式中 % 是取余运算符，百分比格式化要用 f-string。
# 4. 用浮点数直接比较金额是否相等，误差会在后续计算中累积。
