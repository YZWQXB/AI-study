# ==================== 1.4.3 只关注结果不关注过程 ====================
# 结果“看起来对”不代表过程正确。浮点数、整除方向、舍入规则都容易产生偏差。
print("0.1 + 0.2 =", 0.1 + 0.2)              # -> 0.1 + 0.2 = 0.30000000000000004
print("直接比较相等：", 0.1 + 0.2 == 0.3)    # -> 直接比较相等： False
import math

print("按误差比较：", math.isclose(0.1 + 0.2, 0.3))   # -> 按误差比较： True
print("7 // 2 =", 7 // 2, "，-7 // 2 =", -7 // 2)     # -> 7 // 2 = 3 ，-7 // 2 = -4
print("-7 % 2 =", -7 % 2)                             # -> -7 % 2 = 1
# // C++: 整数除法向零截断，-7 / 2 得 -3，-7 % 2 得 -1；
# // Python 的 // 和 % 采用向下取整，符号规则与 C++ 不同。
# 浮点数遵循 IEEE 754 二进制表示，0.1 无法精确存储，金额计算应使用 Decimal 或整数分。

# 常见坑点：
# 1. 背语法点却不写小练习，遇到真实需求仍然无法拆解步骤。
# 2. 复制代码后不检查每行语义，尤其是循环变量和固定下标混用。
# 3. 用 == 比较浮点结果，或用浮点数累加金额导致分位误差。
# 4. 把 Python 的 //、% 与 C++ 当成完全相同，负数场景下结果不同。
