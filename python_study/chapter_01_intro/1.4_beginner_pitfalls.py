# ==================== 1.4.1 只记语法不做练习 ====================
# 记住 range(1, 5) 的语法，不等于能正确表达“1 到 5”。
# range 的右端点不包含在内，这是最常见的差一错误。
wrong_total = sum(range(1, 5))     # 实际计算 1 + 2 + 3 + 4
correct_total = sum(range(1, 6))   # 才是 1 到 5
print("错误结果：", wrong_total)     # -> 错误结果： 10
print("正确结果：", correct_total)   # -> 正确结果： 15
# // C++: for (int i = 1; i <= 5; ++i) 用 <= 表达闭区间；
# // Python 的 range(1, 6) 用“左闭右开”表达同一范围。

# ==================== 1.4.2 只会抄代码不会拆问题 ====================
# 抄来的代码常常“结构正确但语义错误”。下面这段循环看似在累加，
# 实际每一轮都取第一个元素，复制粘贴后很难发现。
scores = [88, 92, 76]
copied_total = 0
for i in range(len(scores)):
    copied_total += scores[0]
print("复制后的错误总分：", copied_total)   # -> 复制后的错误总分： 264

# 先拆问题：遍历每一个元素，累加当前元素，而不是固定下标。
correct_total = 0
for score in scores:
    correct_total += score
print("正确总分：", correct_total)   # -> 正确总分： 256
# // C++: 范围 for（for (int score : scores)）表达同样的“逐元素处理”意图。

