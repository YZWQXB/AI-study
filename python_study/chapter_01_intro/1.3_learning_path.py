# 第 1 章 Python 语言认知与学习方法
# 1.3 Python 学习路径
# 学习优先级：P1（重点掌握） | 掌握要求：会用
# 本文件：用可运行示例理解“语法 -> 问题求解 -> 模块化 -> 规范代码”的递进路径。

# ==================== 1.3.1 从语法学习到问题求解 ====================
# 语法只是表达手段；真正的能力是把需求拆成数据和处理步骤，再翻译成代码。
# 下面把学习阶段表示为数据，再计算总体进度，体会“数据驱动输出”的写法。
stages = [
    ("基础语法", 0.85),
    ("控制结构", 0.80),
    ("数据结构", 0.60),
    ("函数与模块", 0.35),
]
for stage_name, progress in stages:
    print(f"{stage_name}: {progress:.0%}")
# -> 基础语法: 85%
# -> 控制结构: 80%
# -> 数据结构: 60%
# -> 函数与模块: 35%
overall = sum(progress for _, progress in stages) / len(stages)
print(f"平均进度：{overall:.1%}")   # -> 平均进度：65.0%
# // C++: 可用 std::vector<std::pair<std::string, double>> 存储同样数据；
# // C++: Python 的元组与 for 解包让这段代码更短，第 9 章会系统讲解。

# ==================== 1.3.2 从单文件练习到模块化编程 ====================
# 单文件适合练习语法；功能变多后要拆成模块，通过 import 复用。
# 标准库本身就是大量模块，导入后即可使用，不必重复实现常见算法。
import math

print("gcd(252, 105) =", math.gcd(252, 105))   # -> gcd(252, 105) = 21
print("10 的整数平方根 =", math.isqrt(10))     # -> 10 的整数平方根 = 3
# // C++: 需要 #include <numeric> / <cmath> 并调用 std::gcd、std::sqrt；
# // Python 的 import 发生在运行时，第 13 章会讲自定义模块与包。

# ==================== 1.3.3 从可运行代码到规范代码 ====================
# 能运行只是最低要求。规范代码应使用有含义的常量名，避免魔法数字，
# 并把判断规则集中在容易阅读的位置。
PASS_SCORE = 60
EXCELLENT_SCORE = 90
score = 85
level = "优秀" if score >= EXCELLENT_SCORE else ("及格" if score >= PASS_SCORE else "不及格")
print(f"{score} 分的等级：{level}")   # -> 85 分的等级：及格
# // C++: 同样应使用 constexpr 常量代替魔法数字；Python 用全大写命名表达“常量约定”。

# 常见坑点：
# 1. 收藏大量教程却不动手，语法知识无法转化为解题能力。
# 2. 复制代码后只改变量值、不改变量名，导致语义混乱和隐蔽错误。
# 3. 过早追求框架和项目，跳过数据结构、函数、异常等基础能力。
# 4. 认为“能跑就行”，忽视命名、缩进、注释和可测试性。
