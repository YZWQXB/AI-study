import sys

# ==================== 2.2.1 IDLE 的基本使用 ====================
# IDLE 随官方安装包提供，包含编辑器与交互式 Shell。
# 在 Shell 中输入表达式会立即回显结果；按 F5 可运行当前编辑窗口的脚本。
# 适合快速验证语法，不适合组织多文件项目。

# ==================== 2.2.2 VS Code / PyCharm 入门配置 ====================
# 两个编辑器的核心步骤相同：选择解释器、打开项目目录、配置运行入口。
# VS Code 需安装 Python 扩展，并用命令面板选择 Python 3.12 解释器。
# 关键习惯：让编辑器的解释器与终端使用的解释器保持一致，避免版本错位。

# ==================== 2.2.3 终端与命令行基础 ====================
# 常用命令（在项目目录下执行）：
#   python 2.2_editor_and_terminal.py     运行脚本
#   python -c "print(2 ** 10)"            执行一行代码
#   python -m json.tool data.json         以模块方式运行标准库工具
#   python script.py > out.txt            标准输出重定向到文件
#   python script.py | more               管道传给下一个程序
print("当前平台：", sys.platform)            # -> 当前平台： win32
print("命令行参数个数：", len(sys.argv))      # -> 命令行参数个数： 1

# 不带参数运行时，sys.argv 只包含脚本自身；带参数时从下标 1 开始是用户参数。
if len(sys.argv) > 1:
    print("收到的参数：", sys.argv[1:])
else:
    print("未提供参数，使用默认配置")          # -> 未提供参数，使用默认配置
# // C++: main(int argc, char* argv[]) 的 argc/argv 对应 sys.argv 的长度与列表；
# // Python 的列表已经完成分词，不需要手动处理空格与引号。

# 常见坑点：
# 1. IDLE 与终端的工作目录可能不同，相对路径指向的文件也不同。
# 2. Windows 路径含空格时命令要加引号，否则被拆成多个参数。
# 3. 编辑器和终端选中了不同 Python 版本，出现“编辑器能跑、终端报错”。
# 4. 把交互式环境的即时回显当成脚本行为，脚本中忘记写 print 而没有输出。
