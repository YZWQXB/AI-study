# 本文件：区分交互式、脚本式与编辑器运行，并理解 __name__ 的含义。

# ==================== 2.3.1 交互式运行 ====================
# 在终端输入 python 进入 REPL（读取-求值-输出循环）。
# 交互式环境会自动显示表达式结果，适合验证小片段：
#   >>> 1 + 2
#   3
#   >>> "py" * 3
#   'pypypy'
# 退出可输入 exit() 或按 Ctrl+Z 后回车（Windows）。

# ==================== 2.3.2 脚本式运行 ====================
# 把代码保存为 .py 文件后，用 python 文件名 执行。
# 脚本模式不会自动回显表达式结果，必须调用 print 才有输出。
# 下面的代码用脚本运行时会进入 if 分支；被其他模块导入时不会。
print("当前 __name__：", __name__)   # -> 当前 __name__： __main__

if __name__ == "__main__":
    print("作为脚本直接运行")        # -> 作为脚本直接运行
# // C++: 每个程序都有 main 入口，通常由链接器决定入口点；
# // Python 没有强制入口，__name__ == "__main__" 是约定俗成的脚本入口判断。

# ==================== 2.3.3 在编辑器中运行程序 ====================
# 编辑器的“运行”按钮本质是调用所选解释器执行当前文件。
# 需要传入参数或设置工作目录时，应配置 launch.json 或运行配置，而不是写死在代码里。

# 常见坑点：
# 1. 在 REPL 中定义了变量后关闭窗口，变量不会保留到下次运行。
# 2. 脚本没有 print 却期待看到结果，误以为程序没运行。
# 3. 编辑器的运行目录与文件目录不一致，导致相对路径失效。
# 4. 把 __name__ 固定当成 "__main__"，导入模块时它实际上是模块名。
