# ==================== 10.5.1 什么时候用列表 ====================
# 列表有序、可重复、可修改：按下标访问 O(1)，按值查找 O(n)，尾部追加平均 O(1)。
scores = [88, 92, 76, 90]
print(scores[2])                            # -> 76
scores.append(95)
print(scores)                               # -> [88, 92, 76, 90, 95]
print(95 in scores)                         # -> True，需要逐个比较
# // C++: std::vector 支持随机访问，push_back 平均 O(1)，中间插入/删除 O(n)。
# 适用：有先后顺序、允许重复、需要按下标或切片访问的数据。

# ==================== 10.5.2 什么时候用字典 ====================
# 字典按键查找平均 O(1)，适合“按编号或名称取整条记录”，键唯一且可哈希。
score_map = {"S01": 88, "S02": 92, "S03": 76}
print(score_map["S02"])                     # -> 92
score_map["S04"] = 90
print(len(score_map))                       # -> 4
print("S03" in score_map)                   # -> True，判断的是键
print(92 in score_map.values())             # -> True，判断值要显式用 values()
# 按值查找仍需遍历，字典没有自动维护“值到键”的反向索引。
# // C++: std::map 红黑树 O(log n) 且有序；std::unordered_map 哈希平均 O(1) 但无序。

# ==================== 10.5.3 什么时候用集合和元组 ====================
# 集合只保存唯一值，成员判断平均 O(1)，适合黑名单、标签、去重。
blacklist = {"S03", "S05"}
print("S03" in blacklist)                   # -> True
print(len({"S01", "S01", "S02"}))           # -> 2
# 元组有序、不可变、可哈希，适合字段固定的小记录，也能作为字典键。
point = (3.0, 4.5)
print(point[0])                             # -> 3.0
location = {(3.0, 4.5): "A 库位"}
print(location[(3.0, 4.5)])                 # -> A 库位
print(list(point))                          # -> [3.0, 4.5]，需要修改时转成列表

# 选型对照：先问三个问题——需要顺序吗？需要按键定位吗？需要去重吗？
rows = [
    ("列表", "有序、可重复", "按下标取值", "按值 O(n)", "成绩列表、排名"),
    ("字典", "键值映射", "按键取值", "按键平均 O(1)", "学号查记录"),
    ("集合", "唯一、无序", "成员判断", "平均 O(1)", "黑名单、去重"),
    ("元组", "有序、不可变", "按下标取值", "按下标 O(1)", "坐标、固定记录"),
]
print("结构 | 特点 | 主要操作 | 复杂度 | 典型场景")   # -> 结构 | 特点 | 主要操作 | 复杂度 | 典型场景
for name, feature, main_op, cost, scene in rows:
    print(name, "|", feature, "|", main_op, "|", cost, "|", scene)   # -> 见下方四行输出
# -> 列表 | 有序、可重复 | 按下标取值 | 按值 O(n) | 成绩列表、排名
# -> 字典 | 键值映射 | 按键取值 | 按键平均 O(1) | 学号查记录
# -> 集合 | 唯一、无序 | 成员判断 | 平均 O(1) | 黑名单、去重
# -> 元组 | 有序、不可变 | 按下标取值 | 按下标 O(1) | 坐标、固定记录

students_in_order = ["S01", "S02", "S03"]   # 需要顺序：列表
score_by_id = {"S01": 88, "S02": 92}        # 需要按编号定位：字典
banned_ids = {"S03", "S05"}                 # 需要去重或存在性判断：集合
fixed_record = ("S01", 88)                  # 字段固定且不修改：元组
print(score_by_id[fixed_record[0]])         # -> 88
# // C++: 选型同样是 vector / map / unordered_set / pair 的取舍，先看操作复杂度再看语义。

# 常见坑点：
# 1. 用列表循环查找代替字典：数据量 n 大时是 O(n)，而字典按键是平均 O(1)。
# 2. 数据本身有重复却用集合或字典键保存，会悄悄丢掉重复项。原因：集合与字典键要求唯一。需要保留全部记录时用列表。
# 3. 需要固定顺序却用集合，遍历顺序不可依赖。原因：集合不保存位置。需要顺序输出时用 sorted() 或改用列表。
# 4. 元组的不可变只到第一层：元组里放列表，列表内容仍然可以修改。原因：元组只冻结直接元素。
#    需要完全不可变时改用 frozenset，或把内部元素也换成元组。
# 5. 字典平均 O(1) 不等于最坏 O(1)，哈希冲突严重时会退化。原因：冲突时退化为线性查找。要求稳定有序查找时考虑排序后的列表或 C++ 的 map。
