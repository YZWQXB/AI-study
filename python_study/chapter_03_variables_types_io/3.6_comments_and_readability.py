# 3.6 注释与代码可读性

# 3.6.1 单行注释
# Python 用 # 开始单行注释；解释器执行时会忽略井号后面的说明文字。
score = 90  # 行尾也可以写注释，说明这个值代表什么
print(score)
# // C++: 单行注释使用 //，例如 int score = 90; // 当前成绩

# 注释应解释“为什么”或补充读者需要的背景，不要重复代码本身。
# 不推荐：score = score + 1  # score 加 1
# 更清楚：score += 1  # 完成一次练习后增加一分（此处只是演示）
score += 1

# 3.6.2 多行说明文本
# 连续使用多个 # 是清晰、常见的多行注释写法。
# 程序的主要步骤：
# 1. 保存成绩
# 2. 计算更新后的成绩
# 3. 输出结果
print("更新后的成绩：", score)

# 三引号字符串主要用于文档字符串（docstring），通常写在模块、函数或类定义开头。
# 这里用一个简单函数演示；函数定义会在后续章节详细学习。
def show_message():
    """显示一条学习提示。"""
    print("认真阅读代码，也要动手运行。")

show_message()
# // C++: 可用 /* ... */ 写多行注释；C++ 没有与 Python docstring 完全相同的运行时文档字符串。

# 3.6.3 基础书写规范
# 使用有意义的变量名、合理空格和空行；每行代码表达一个清楚的步骤。
item_price = 8.5
item_count = 2
total_price = item_price * item_count
print(f"总价：{total_price:.2f}")
# // C++ 常见约定也鼓励清晰命名、统一缩进和合理分段。
