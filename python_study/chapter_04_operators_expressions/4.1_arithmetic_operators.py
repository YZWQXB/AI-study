# 第 4 章 运算符与表达式
# 4.1 算术运算符

# 4.1.1 加减乘除：+、-、*、/ 的基本含义与 C++ 类似。
a = 7
b = 2
print("加法：", a + b)             # // C++: a + b
print("减法：", a - b)             # // C++: a - b
print("乘法：", a * b)             # // C++: a * b

# Python 的 / 执行普通除法，即使两个操作数都是 int，结果也为 float。
print("普通除法：", a / b)        # 3.5
print("整除数值：", 8 / 2)         # 4.0，仍是 float
# // C++: 7 / 2 得到 3；要得到 3.5，至少一个操作数应为浮点数，如 7.0 / 2

# 4.1.2 整除、取余与幂运算
# // 是向下取整的整除运算；负数时与 C++ 的向零截断不同。
print("整除：", 7 // 2)           # 3
print("负数整除：", -7 // 2)      # -4
# // C++: -7 / 2 得到 -3（C++11 起向零截断）

# % 计算余数。Python 的余数符号跟随除数；负数时 C++ 的规则不同。
print("取余：", 7 % 2)            # 1
print("负数取余：", -7 % 2)       # 1
# // C++: -7 % 2 得到 -1，余数符号跟随被除数

# ** 是乘方；C++ 的 ^ 表示按位异或，不是乘方。
print("3 的 2 次方：", 3 ** 2)     # 9
# // C++: std::pow(3, 2)，需要包含 <cmath>

# 4.1.3 运算优先级与括号
# 乘除优先于加减；括号可明确表达希望先计算的部分。
print("2 + 3 * 4 =", 2 + 3 * 4)   # 14
print("(2 + 3) * 4 =", (2 + 3) * 4) # 20
# // C++ 的优先级规则相似；复杂表达式应使用括号提高可读性。
